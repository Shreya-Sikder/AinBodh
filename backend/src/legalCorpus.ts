/**
 * Score every passage by the concept terms it contains (rarer terms weigh
 * more), then return the best-matching sections inside the top passages.
 * Repealed acts are excluded unless `allowActFiles` lists them.
 */
export function searchByConcepts(
  concepts: string[],
  options: {
    limit?: number;
    boostActFiles?: Set<string>;
    allowActFiles?: Set<string>;
  } = {},
): SectionHit[] {
  if (passages.length === 0 || concepts.length === 0) return [];

  const terms = Array.from(
    new Set(
      concepts
        .map((term) => normalizeForSearch(term).trim())
        .filter((term) => term.length >= 3),
    ),
  ).slice(0, 40);

  if (terms.length === 0) return [];

  // Document frequency per term (one pass).
  const df = new Map<string, number>();
  const contains: Array<Array<number>> = [];
  const normalizedTexts: string[] = new Array(passages.length);

  for (let p = 0; p < passages.length; p++) {
    const lawStatus = status.get(passages[p].actFile);
    if (lawStatus?.repealed && !options.allowActFiles?.has(passages[p].actFile)) {
      contains.push([]);
      continue;
    }

    const text = normalizeForSearch(passages[p].text);
    normalizedTexts[p] = text;
    const hits: number[] = [];
    terms.forEach((term, t) => {
      if (text.includes(term)) {
        hits.push(t);
        df.set(term, (df.get(term) ?? 0) + 1);
      }
    });
    contains.push(hits);
  }

  const total = passages.length;
  const idf = terms.map((term) => Math.log(1 + total / (1 + (df.get(term) ?? 0))));

  const scoredPassages: Array<{ index: number; score: number }> = [];
  contains.forEach((hits, index) => {
    if (hits.length === 0) return;
    let score = hits.reduce((sum, t) => sum + idf[t], 0);
    const actFile = passages[index].actFile;
    if (options.boostActFiles?.has(actFile)) score *= 1.6;
    if (status.get(actFile)?.amending) score *= 0.8;
    scoredPassages.push({ index, score });
  });

  scoredPassages.sort((a, b) => b.score - a.score);

  const hits: SectionHit[] = [];
  const seen = new Set<string>();

  for (const { index } of scoredPassages.slice(0, 40)) {
    const passage = passages[index];

    for (const section of splitSections(passage.text)) {
      const sectionText = normalizeForSearch(section.text);
      const matched = terms.filter((term) => sectionText.includes(term));
      if (matched.length === 0) continue;
      if (isRepealedSectionText(section.text)) continue;

      const key = `${passage.actFile}:${section.sectionNumber ?? passage.id}`;
      if (seen.has(key)) continue;
      seen.add(key);

      let score = matched.reduce((sum, term) => sum + idf[terms.indexOf(term)], 0);
      if (options.boostActFiles?.has(passage.actFile)) score *= 1.6;
      if (status.get(passage.actFile)?.amending) score *= 0.8;
      // A numbered section is a citable unit; a definitions lead-in is weaker.
      if (!section.sectionNumber) score *= 0.6;

      hits.push({
        actFile: passage.actFile,
        title: passage.title,
        sectionNumber: section.sectionNumber,
        text: section.text,
        score,
        matchedTerms: matched,
        passageId: passage.id,
      });
    }
  }

  return hits.sort((a, b) => b.score - a.score).slice(0, options.limit ?? 24);
}

/** Follow "repealed by" links to the law currently in force (guards against cycles). */
export function currentLawFor(actFile: string): string | undefined {
  let current = actFile;
  const seen = new Set<string>();
  while (status.get(current)?.repealed && status.get(current)?.replacementActFile && !seen.has(current)) {
    seen.add(current);
    current = status.get(current)!.replacementActFile!;
  }
  return status.get(current)?.repealed ? undefined : current === actFile ? undefined : current;
}

/** A section printed as repealed/omitted, e.g. "৫৭। [রহিত]" or "57. [Omitted.]". */
export function isRepealedSectionText(text: string): boolean {
  const head = canonical(text).slice(0, 140);
  return (
    /^[^\s]{1,5}\s*[।৷.]?\s*\[?\s*(?:রহিত|বিলুপ্ত|repealed|omitted)/i.test(head) ||
    /\[\s*(?:রহিত|বিলুপ্ত|Repealed|Omitted)[^\]]{0,80}\]\s*$/i.test(head.trim()) && head.trim().length < 140
  );
}

/** Acts whose title matches any of the given law names (Bangla or English). */
export function findActsByName(names: string[]): Set<string> {
  const result = new Set<string>();
  const wanted = names.map(normalizeTitle).filter((name) => name.length >= 4);
  if (wanted.length === 0) return result;

  for (const lawStatus of status.values()) {
    const title = normalizeTitle(lawStatus.title);
    for (const name of wanted) {
      const year = name.match(/\b(1[89]\d\d|20\d\d)\b/)?.[1];
      if (year && !title.includes(year)) continue;
      const nameWords = name.replace(/\b\d{4}\b/g, "").split(" ").filter((word) => word.length >= 3);
      if (nameWords.length === 0) continue;
      const overlap = nameWords.filter((word) => title.includes(word)).length / nameWords.length;
      if (overlap >= 0.75) result.add(lawStatus.actFile);
    }
  }

  return result;
}

/** True when the user's own words name this (repealed) law, so it may be discussed. */
export function questionNamesAct(question: string, actFile: string): boolean {
  const lawStatus = status.get(actFile);
  if (!lawStatus) return false;
  const q = normalizeTitle(question);
  const title = normalizeTitle(lawStatus.title).replace(/\b(the|act|ordinance|আইন|অধ্যাদেশ)\b/g, " ").replace(/\s+/g, " ").trim();
  const year = title.match(/\b(1[89]\d\d|20\d\d)\b/)?.[1];
  const words = title.replace(/\b\d{4}\b/g, "").split(" ").filter((word) => word.length >= 3);
  if (words.length === 0) return false;
  const overlap = words.filter((word) => q.includes(word)).length / words.length;
  return overlap >= 0.8 && (!year || q.includes(year));
}

/**
 * Cross-language version: the planner identified this act from the question
 * (possibly translating an English name to the Bangla title), and the question
 * contains the act's year, e.g. "Digital Security Act 2018" -> ডিজিটাল নিরাপত্তা আইন, ২০১৮.
 */
export function questionReferencesActYear(question: string, actFile: string): boolean {
  const lawStatus = status.get(actFile);
  if (!lawStatus) return false;
  const year = toAsciiDigits(lawStatus.title).match(/\b(1[89]\d\d|20\d\d)\b/)?.[1];
  return Boolean(year && toAsciiDigits(question).includes(year));
}

/* =========================================================
   LOCAL LEGAL CORPUS — law status + concept search

   Reads data/rag_passages.jsonl (the same corpus ingested into Supabase).

   1. LAW STATUS. data/metadata.csv's `repealed` column is not usable: it
      marks 954 of 1,570 acts as repealed, including the Penal Code and the
      Code of Criminal Procedure, because it fires on any mention of the word.
      bdlaws itself prints an explicit banner directly after the act number
      of a repealed act, e.g.
        "( ২০২৩ সনের ৩৯ নং আইন ) এই আইন সাইবার সুরক্ষা অধ্যাদেশ, ২০২৫ (...) দ্বারা রহিত করা হইয়াছে।"
      That banner is the status signal used here.

   2. CONCEPT SEARCH. A fast scan of every passage for legal concept terms
      (Bangla + English), so a plain-language question is matched against
      the words statutes actually use, not the user's words.

   If the corpus file is missing, status falls back to data/law-status.json
   (generated by `npx tsx src/buildLawStatus.ts`) and concept search is skipped.
========================================================= */

import fs from "node:fs";
import path from "node:path";

export type LawStatus = {
  actFile: string;
  title: string;
  repealed: boolean;
  /** The law that repealed it, as named in the banner, if any. */
  repealedBy?: string;
  /** act_file of the replacement, when it exists in the corpus. */
  replacementActFile?: string;
  /** Amending acts/ordinances ("(সংশোধন)", "(Amendment)") change another law. */
  amending: boolean;
  /** Where the status came from: the corpus snapshot or the live bdlaws page. */
  source?: "corpus" | "live";
  /** True for acts loaded from bdlaws after the corpus snapshot. */
  live?: boolean;
};

export type CorpusPassage = {
  id: string;
  actFile: string;
  title: string;
  text: string;
};

export type SectionHit = {
  actFile: string;
  title: string;
  sectionNumber: string | null;
  text: string;
  score: number;
  matchedTerms: string[];
  passageId: string;
};

const CORPUS_PATH =
  process.env.LEGAL_CORPUS_PATH || path.resolve(__dirname, "..", "..", "data", "rag_passages.jsonl");

const STATUS_PATH =
  process.env.LAW_STATUS_PATH || path.resolve(__dirname, "..", "data", "law-status.json");

/* ---------------------------------------------------------
   Text helpers
--------------------------------------------------------- */

const BANGLA_DIGITS = "০১২৩৪৫৬৭৮৯";

export function toAsciiDigits(value: string): string {
  return value.replace(/[০-৯]/g, (digit) => String(BANGLA_DIGITS.indexOf(digit)));
}

/** NFC + unify the two encodings of য় + drop joiners, lower-case Latin. */
export function normalizeForSearch(value: string): string {
  return value
    .normalize("NFC")
    .replace(/য়/g, "য়")
    .replace(/ড়/g, "ড়")
    .replace(/ঢ়/g, "ঢ়")
    .replace(/[​-‍﻿]/g, "")
    .replace(/�/g, "")
    .toLowerCase();
}

export function normalizeTitle(value: string): string {
  return toAsciiDigits(normalizeForSearch(value))
    .replace(/[(),.;:।'"“”‘’\-–]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/* ---------------------------------------------------------
   Repeal banner detection
--------------------------------------------------------- */

// Banner directly after the act-number bracket, e.g. "( ২০১৮ সনের ৪৬ নং আইন ) এই আইন … দ্বারা রহিত করা হইয়াছে"
// "য়" is written as either U+09DF or U+09AF U+09BC in the corpus; both are accepted.
const YA = "(?:\u09DF|\u09AF\u09BC)";
const ACT_BRACKET = /\(\s*(?:[০-৯0-9]{4}\s*(?:সনের|সালের)\s*[০-৯0-9]+\s*(?:নং|নম্বর)?\s*(?:আইন|অধ্যাদেশ|আদেশ|প্রবিধান|রাষ্ট্রপতির আদেশ)|(?:ACT|ORDINANCE|ORDER|REGULATION|P\.?\s*O\.?)\s*NO\.?\s*[^)]{1,40})\s*\)/i;
const BN_BANNER = new RegExp(
  `^\\s*\\S{0,3}\\s*এই\\s+(?:আইন|অধ্যাদেশ|আদেশ|প্রবিধান)(?:টি)?\\s+([\\s\\S]{0,260}?)\\s*দ্বারা\\s+রহিত(?:\\s+করা)?\\s+হই${YA}াছে`,
);
const EN_BANNER = /^\s*\S{0,3}\s*(?:This\s+(?:Act|Ordinance|Order|Regulation)\s+(?:is|has\s+been|was)\s+repealed\s+by\s+([^.\[]{3,200})|\[\s*Repealed\s+by\s+([^\]]{3,200})\])/i;

/** Unicode-normalise without changing case, so indexes stay valid for display text. */
function canonical(value: string): string {
  return value
    .normalize("NFC")
    .replace(/\u09AF\u09BC/g, "\u09DF")
    .replace(/[\u200B-\u200D\uFEFF]/g, "")
    .replace(/\uFFFD/g, "");
}

function detectRepeal(text: string): { repealed: boolean; repealedBy?: string } {
  const head = canonical(text);
  const bracket = head.match(ACT_BRACKET);
  if (!bracket || bracket.index === undefined || bracket.index > 400) return { repealed: false };

  const after = head.slice(bracket.index + bracket[0].length, bracket.index + bracket[0].length + 420);

  const bn = after.match(BN_BANNER);
  if (bn) return { repealed: true, repealedBy: cleanLawName(bn[1]) };

  const en = after.match(EN_BANNER);
  if (en) return { repealed: true, repealedBy: cleanLawName(en[1] || en[2] || "") };

  return { repealed: false };
}

export type RepealBanner = { repealed: boolean; repealedBy?: string };

const BN_BANNER_ANYWHERE = new RegExp(
  `এই\\s+(?:আইন|অধ্যাদেশ|আদেশ|প্রবিধান|রাষ্ট্রপতির\\s+আদেশ)(?:টি)?\\s+([^।৷\\n]{3,300}?)\\s*(?:দ্বারা|কর্তৃক)\\s+রহিত(?:\\s+করা)?\\s+হই${YA}াছে`,
);
const EN_BANNER_ANYWHERE =
  /This\s+(?:Act|Ordinance|Order|Regulation|President'?s\s+Order)\s+(?:has\s+been|is|was|stands)\s+repealed\s+by\s+(?:the\s+)?([^.\n\[]{3,200})|\[\s*Repealed\s+by\s+([^\]]{3,200})\]/i;

/**
 * Repeal notice anywhere near the top of a live act page (the page layout,
 * unlike the corpus text, isn't guaranteed to put it right after the act number).
 * Only the opening of the act is searched, so a section of a current law that
 * mentions other laws it repealed is not mistaken for a notice about itself.
 */
export function detectRepealBanner(pageText: string): RepealBanner {
  const text = canonical(pageText);
  const bracket = text.match(ACT_BRACKET);
  const start = bracket?.index !== undefined ? Math.max(0, bracket.index - 300) : 0;
  const window = text.slice(start, start + (bracket ? 1800 : 4000));

  const bn = window.match(BN_BANNER_ANYWHERE);
  if (bn) return { repealed: true, repealedBy: cleanLawName(bn[1]) };
  const en = window.match(EN_BANNER_ANYWHERE);
  if (en) return { repealed: true, repealedBy: cleanLawName(en[1] || en[2] || "") };
  return { repealed: false };
}

export function cleanLawName(value: string): string {
  return value
    .replace(/\(\s*[০-৯0-9]{4}\s*(?:সনের|সালের)[^)]*\)/g, "")
    .replace(/\((?:Act|Ordinance)\s+No[^)]*\)/gi, "")
    .replace(/\s+/g, " ")
    .replace(/^the\s+/i, "")
    .replace(/[\s.।৷,;:]+$/, "")
    .trim();
}


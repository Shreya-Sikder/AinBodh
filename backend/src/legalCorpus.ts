/**
 * Split passage text into sections. A section number stands alone and is
 * followed by "." / "।" / "৷" and whitespace (e.g. "registration 1. Any",
 * "২৫। (১) যদি"). Text before the first number is returned with null number.
 */
export function splitSections(text: string): Array<{ sectionNumber: string | null; text: string }> {
  const clean = text.replace(/�+/g, "");
  const regex = /(?<![0-9০-৯\[\(./-])([০-৯]{1,3}|[0-9]{1,3})\s?[।৷.](?=\s)/g;
  const marks: Array<{ number: string; index: number }> = [];
  let match: RegExpExecArray | null;

  while ((match = regex.exec(clean)) !== null) {
    const number = toAsciiDigits(match[1]);
    const n = Number(number);
    if (Number.isInteger(n) && n >= 1 && n <= 999) marks.push({ number: String(n), index: match.index });
  }

  const out: Array<{ sectionNumber: string | null; text: string }> = [];
  if (marks.length === 0) return [{ sectionNumber: null, text: clean.trim() }];

  const lead = clean.slice(0, marks[0].index).trim();
  if (lead.length > 80) out.push({ sectionNumber: null, text: lead });

  marks.forEach((mark, index) => {
    const end = index + 1 < marks.length ? marks[index + 1].index : clean.length;
    const body = clean.slice(mark.index, end).trim();
    if (body.length > 20) out.push({ sectionNumber: mark.number, text: body.slice(0, 6500) });
  });

  return out;
}


let passages: CorpusPassage[] = [];
let passagesByAct = new Map<string, CorpusPassage[]>();
let status = new Map<string, LawStatus>();
let loaded = false;
let corpusAvailable = false;
let loading: Promise<void> | null = null;

export function isCorpusAvailable(): boolean {
  return corpusAvailable;
}

/** Title -> act_file lookup over everything loaded (snapshot + live). */
export function findActByTitle(name: string | undefined): string | undefined {
  if (!name) return undefined;
  const byTitle = new Map<string, string>();
  for (const item of status.values()) byTitle.set(normalizeTitle(item.title), item.actFile);
  return resolveReplacement(name, byTitle);
}

export function hasActText(actFile: string): boolean {
  return (passagesByAct.get(actFile)?.length ?? 0) > 0;
}

/**
 * Record a repeal found on the live bdlaws page. Only ever marks a law as
 * repealed — a page that fails to show a notice never un-repeals a law the
 * corpus says is repealed.
 */
export function applyLiveStatus(
  actFile: string,
  live: { repealed: boolean; repealedBy?: string; replacementActFile?: string; title?: string },
): boolean {
  if (!live.repealed) return false;
  const current = status.get(actFile);
  const replacementActFile = live.replacementActFile || findActByTitle(live.repealedBy) || current?.replacementActFile;
  const changed =
    !current?.repealed || (replacementActFile !== undefined && replacementActFile !== current.replacementActFile);

  status.set(actFile, {
    actFile,
    title: current?.title || live.title || actFile,
    repealed: true,
    repealedBy: live.repealedBy || current?.repealedBy,
    replacementActFile,
    amending: current?.amending ?? isAmendingTitle(live.title || ""),
    source: "live",
    live: current?.live,
  });
  return changed;
}

/** Add an act fetched from bdlaws after the snapshot (one passage per section). */
export function addLiveAct(
  actFile: string,
  title: string,
  sections: Array<{ sectionNumber: string | null; text: string }>,
  repeal: RepealBanner = { repealed: false },
) {
  const existing = passagesByAct.get(actFile);
  if (existing?.length) {
    const ids = new Set(existing.map((passage) => passage.id));
    passages = passages.filter((passage) => !ids.has(passage.id));
  }

  const added: CorpusPassage[] = sections
    .filter((section) => section.text.trim().length > 20)
    .map((section, index) => ({
      id: `live:${actFile}:${section.sectionNumber ?? `p${index}`}`,
      actFile,
      title,
      text: section.text,
    }));
  if (added.length === 0) return;

  passages = passages.concat(added);
  passagesByAct.set(actFile, added);

  const previous = status.get(actFile);
  status.set(actFile, {
    actFile,
    title,
    repealed: previous?.repealed || repeal.repealed,
    repealedBy: previous?.repealedBy || repeal.repealedBy,
    replacementActFile: previous?.replacementActFile || findActByTitle(repeal.repealedBy),
    amending: isAmendingTitle(title),
    source: previous?.source ?? (repeal.repealed ? "live" : "corpus"),
    live: true,
  });

  // A law that names this one as its replacement can now be linked to it.
  const key = normalizeTitle(title);
  for (const item of status.values()) {
    if (item.repealed && !item.replacementActFile && item.repealedBy) {
      const by = normalizeTitle(item.repealedBy);
      if (by === key || (key.length > 6 && (by.includes(key) || key.includes(by)))) item.replacementActFile = actFile;
    }
  }
}

export function getLawStatus(actFile: string): LawStatus | undefined {
  return status.get(actFile);
}

export function allLawStatuses(): LawStatus[] {
  return Array.from(status.values());
}

function isAmendingTitle(title: string): boolean {
  return /\(\s*(?:সংশোধন|দ্বিতীয় সংশোধন|তৃতীয় সংশোধন|amendment|second amendment|third amendment)\s*\)|সংশোধন\)|amendment\)/i.test(
    title,
  );
}

function resolveReplacement(name: string | undefined, byTitle: Map<string, string>): string | undefined {
  if (!name) return undefined;
  const key = normalizeTitle(name);
  if (byTitle.has(key)) return byTitle.get(key);
  // Loose match: same title words, ignoring punctuation/spacing.
  for (const [title, actFile] of byTitle) {
    if (title.length > 6 && (key.includes(title) || title.includes(key))) return actFile;
  }
  return undefined;
}

export async function loadLegalCorpus(): Promise<void> {
  if (loaded) return;
  if (loading) return loading;

  loading = (async () => {
    if (fs.existsSync(CORPUS_PATH)) {
      const started = Date.now();
      const raw = fs.readFileSync(CORPUS_PATH, "utf8");
      const nextPassages: CorpusPassage[] = [];

      for (const line of raw.split("\n")) {
        if (!line.trim()) continue;
        try {
          const row = JSON.parse(line);
          if (typeof row.text !== "string" || typeof row.act_file !== "string") continue;
          nextPassages.push({
            id: String(row.id ?? `${row.act_file}:${nextPassages.length}`),
            actFile: row.act_file,
            title: String(row.title ?? ""),
            text: row.text,
          });
        } catch {
          // Skip malformed lines.
        }
      }

      passages = nextPassages;
      passagesByAct = new Map();
      for (const passage of passages) {
        const list = passagesByAct.get(passage.actFile) ?? [];
        list.push(passage);
        passagesByAct.set(passage.actFile, list);
      }

      const byTitle = new Map<string, string>();
      for (const [actFile, list] of passagesByAct) byTitle.set(normalizeTitle(list[0].title), actFile);

      status = new Map();
      for (const [actFile, list] of passagesByAct) {
        const title = list[0].title;
        let found: { repealed: boolean; repealedBy?: string } = { repealed: false };
        // The banner sits in the act's opening passage; check the passages that start with the title.
        for (const passage of list) {
          const head = passage.text.slice(0, 700);
          if (!ACT_BRACKET.test(canonical(head))) continue;
          found = detectRepeal(head);
          if (found.repealed) break;
        }

        status.set(actFile, {
          actFile,
          title,
          repealed: found.repealed,
          repealedBy: found.repealedBy,
          replacementActFile: resolveReplacement(found.repealedBy, byTitle),
          amending: isAmendingTitle(title),
        });
      }

      corpusAvailable = true;
      const repealedCount = Array.from(status.values()).filter((item) => item.repealed).length;
      console.log(
        `Legal corpus: ${passages.length} passages, ${passagesByAct.size} acts, ${repealedCount} repealed (${Date.now() - started} ms)`,
      );
    } else if (fs.existsSync(STATUS_PATH)) {
      const data = JSON.parse(fs.readFileSync(STATUS_PATH, "utf8")) as LawStatus[];
      status = new Map(data.map((item) => [item.actFile, item]));
      console.warn(`Legal corpus not found at ${CORPUS_PATH}; using law status file only (concept search disabled).`);
    } else {
      console.warn("Legal corpus and law-status.json not found; repealed-law filtering and concept search are disabled.");
    }

    loaded = true;
  })();

  return loading;
}

